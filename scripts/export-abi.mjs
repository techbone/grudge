// Copies Grudge's ABI from the forge build into the web app as a typed const.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { abi } = JSON.parse(readFileSync(join(root, "contracts/out/Grudge.sol/Grudge.json"), "utf8"));
const out = `// Generated by scripts/export-abi.mjs. Do not edit.\nexport const grudgeAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
writeFileSync(join(root, "web/src/lib/grudge-abi.ts"), out);
console.log(`wrote ${abi.length} ABI entries`);
